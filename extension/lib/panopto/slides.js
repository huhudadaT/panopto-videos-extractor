// Turning the DeliveryInfo `Timestamps` array into a downloadable slide deck.
//
// Each timestamp carries an ObjectSequenceNumber (a big sparse integer like
// 65537, 131073, 196610 — it is not an index) and the PID of the event target
// that produced it. Those two give us the image path on the CDN. When the CDN
// path is wrong for a tenant we fall back to the two same-origin proxies the
// viewer itself uses, both of which 302 to the real asset.

import { pad, slugify, timecode } from "../core/util.js";
import { SLIDE_SIZE } from "../core/constants.js";

/**
 * Every URL worth trying for one slide, in order of preference.
 * @returns {string[]}
 */
export function slideUrlCandidates(model, slide, size = SLIDE_SIZE.FULL) {
  const candidates = [];
  const folder = size === SLIDE_SIZE.THUMB ? "thumbs" : "images";

  if (model.cdnSessionBase && slide.objectPid) {
    candidates.push(
      `${model.cdnSessionBase}/${slide.objectPid}_et/${folder}/slide${slide.seq}.jpg`
    );
    // If full-res is missing the thumb usually still exists.
    if (size !== SLIDE_SIZE.THUMB) {
      candidates.push(
        `${model.cdnSessionBase}/${slide.objectPid}_et/thumbs/slide${slide.seq}.jpg`
      );
    }
  }

  if (model.origin && slide.objectId) {
    candidates.push(
      `${model.origin}/Panopto/Pages/Viewer/Image.aspx?id=${encodeURIComponent(
        slide.objectId
      )}&number=${encodeURIComponent(slide.seq)}`
    );
  }

  if (model.origin && slide.objectPid && model.sessionId) {
    const params = new URLSearchParams({
      eventTargetPID: slide.objectPid,
      sessionPID: model.sessionId,
      number: slide.seq,
      isPrimary: "false",
    });
    if (slide.absoluteTime != null) params.set("absoluteTime", String(slide.absoluteTime));
    candidates.push(`${model.origin}/Panopto/Pages/Viewer/Thumb.aspx?${params.toString()}`);
  }

  return candidates;
}

/**
 * Build the ordered slide manifest. Durations from Panopto occasionally
 * disagree with the gap to the next slide by a few milliseconds; we trust the
 * gaps so the timeline always sums to the session duration exactly.
 */
export function buildSlideManifest(model, options = {}) {
  const size = options.size || SLIDE_SIZE.FULL;
  const total = model.durationSec || 0;
  const width = String(model.slides.length).length + 1;

  return model.slides.map((slide, index) => {
    const next = model.slides[index + 1];
    const end = next ? next.time : Math.max(slide.time, total);
    const duration = Math.max(0.04, end - slide.time);
    const label = slide.caption ? slugify(slide.caption, 48) : "slide";
    return {
      index,
      seq: slide.seq,
      time: slide.time,
      duration,
      caption: slide.caption,
      text: slide.text,
      filename: `${pad(index + 1, width)}-${label}.jpg`,
      urls: slideUrlCandidates(model, slide, size),
    };
  });
}

/** JSON sidecar describing the deck and its timing. */
export function buildTimeline(model, manifest) {
  return {
    generator: "Lectern",
    session: {
      name: model.name,
      folder: model.folder,
      presenter: model.presenter,
      deliveryId: model.deliveryId,
      durationSec: model.durationSec,
      audioOnly: model.isPrimaryAudioOnly,
      viewerUrl: model.origin
        ? `${model.origin}/Panopto/Pages/Viewer.aspx?id=${model.deliveryId}`
        : null,
    },
    slides: manifest.map((slide) => ({
      index: slide.index,
      file: slide.filename,
      sequenceNumber: slide.seq,
      startSec: Number(slide.time.toFixed(3)),
      durationSec: Number(slide.duration.toFixed(3)),
      startTimecode: timecode(slide.time),
      caption: slide.caption || null,
      text: slide.text || null,
    })),
  };
}

/**
 * ffmpeg concat-demuxer list. Pairs with the shell script below so a slide
 * bundle plus an audio file can be turned into a video offline.
 */
export function buildConcatList(manifest) {
  const lines = ["# ffmpeg concat demuxer list, generated by Lectern"];
  for (const slide of manifest) {
    lines.push(`file '${slide.filename.replace(/'/g, "'\\''")}'`);
    lines.push(`duration ${slide.duration.toFixed(3)}`);
  }
  // The concat demuxer drops the final entry's duration unless the last file is
  // repeated, so repeat it.
  const last = manifest[manifest.length - 1];
  if (last) lines.push(`file '${last.filename.replace(/'/g, "'\\''")}'`);
  return `${lines.join("\n")}\n`;
}

export function buildBuildScript(audioFilename, outputFilename) {
  return `#!/usr/bin/env bash
# Rebuild this lecture as a video from the slide stills and the audio track.
# Requires ffmpeg on PATH.
set -euo pipefail

AUDIO="\${1:-${audioFilename}}"
OUT="\${2:-${outputFilename}}"

if [ ! -f "$AUDIO" ]; then
  echo "Audio file not found: $AUDIO" >&2
  echo "Download the audio for this session and pass it as the first argument." >&2
  exit 1
fi

ffmpeg -hide_banner \\
  -f concat -safe 0 -i slides.txt \\
  -i "$AUDIO" \\
  -c:v libx264 -preset veryfast -crf 24 -pix_fmt yuv420p \\
  -vf "scale=1280:-2:force_original_aspect_ratio=decrease,pad=1280:720:(ow-iw)/2:(oh-ih)/2:color=white,fps=2" \\
  -c:a aac -b:a 128k \\
  -shortest -movflags +faststart \\
  "$OUT"

echo "Wrote $OUT"
`;
}

/** Plain-text outline of the deck — handy for pasting into notes. */
export function buildOutline(model, manifest) {
  const lines = [model.name];
  if (model.folder) lines.push(model.folder);
  if (model.presenter) lines.push(model.presenter);
  lines.push("");
  for (const slide of manifest) {
    lines.push(`[${timecode(slide.time)}] ${slide.caption || `Slide ${slide.index + 1}`}`);
    if (slide.text && slide.text !== slide.caption) {
      lines.push(`    ${slide.text.replace(/\s+/g, " ").slice(0, 600)}`);
    }
  }
  return `${lines.join("\n")}\n`;
}
